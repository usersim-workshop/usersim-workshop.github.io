// Regenerates only the SPHERE array at higher density, reusing GRID / LAND_D /
// REGIONS from the existing geo-data.js. Denser land points are needed so the
// USERSIM lettering has enough substrate dots to read.

import { readFileSync, writeFileSync } from "node:fs";
import * as topojson from "topojson-client";
import { geoContains } from "d3-geo";

const N = 46000;

const topo = JSON.parse(readFileSync("node_modules/world-atlas/land-50m.json", "utf8"));
const land = topojson.feature(topo, topo.objects.land);

const golden = Math.PI * (3 - Math.sqrt(5));
const sphere = [];
for (let i = 0; i < N; i++) {
  const y = 1 - (i / (N - 1)) * 2;
  const r = Math.sqrt(1 - y * y);
  const th = golden * i;
  const lat = (Math.asin(y) * 180) / Math.PI;
  const lon = (Math.atan2(Math.sin(th) * r, Math.cos(th) * r) * 180) / Math.PI;
  if (geoContains(land, [lon, lat])) {
    sphere.push([Math.round(lon * 10) / 10, Math.round(lat * 10) / 10]);
  }
  if (i % 5000 === 0) process.stderr.write(`  ${i}/${N}\n`);
}

const src = readFileSync("../geo-data.js", "utf8");
const grid = src.match(/GRID: (\[[\s\S]*?\]),\n/)[1];
const landD = src.match(/LAND_D: ("(?:[^"\\]|\\.)*"),\n/)[1];
const regions = src.match(/REGIONS: (\[[\s\S]*?\])\n\};/)[1];

writeFileSync(
  "../geo-data.js",
  `/* Generated by .geobuild from Natural Earth (world-atlas).
   Land samples from land-50m, outline from land-110m. Public domain.
   Do not hand-edit; regenerate with gen.mjs / densify.mjs / patch-path.mjs. */
window.GEO = {
  SPHERE: ${JSON.stringify(sphere)},
  GRID: ${grid},
  LAND_D: ${landD},
  REGIONS: ${regions}
};
`
);
process.stderr.write(`DONE sphere points: ${sphere.length}\n`);
