// Generates compact land geometry for the workshop graphics.
// Source: Natural Earth via the world-atlas package.
//
//   node gen.mjs > ../geo-data.js
//
// Emits:
//   SPHERE  equal-area land samples (Fibonacci sphere) -> for the dot globe
//   GRID    lat/lon grid land samples                  -> for the flat dot map
//   LAND_D  equirectangular land outline as an SVG path
//   REGIONS a geographically spread set of anchor points

import { readFileSync } from "node:fs";
import * as topojson from "topojson-client";
import { geoContains, geoPath, geoEquirectangular } from "d3-geo";

const topo = JSON.parse(readFileSync("node_modules/world-atlas/land-50m.json", "utf8"));
const land = topojson.feature(topo, topo.objects.land);

/* ---- 1. equal-area sphere sampling (Fibonacci lattice) ---- */
function fibonacciSphere(n) {
  const pts = [];
  const golden = Math.PI * (3 - Math.sqrt(5));
  for (let i = 0; i < n; i++) {
    const y = 1 - (i / (n - 1)) * 2;
    const r = Math.sqrt(1 - y * y);
    const theta = golden * i;
    const x = Math.cos(theta) * r;
    const z = Math.sin(theta) * r;
    const lat = (Math.asin(y) * 180) / Math.PI;
    const lon = (Math.atan2(z, x) * 180) / Math.PI;
    pts.push([lon, lat]);
  }
  return pts;
}

const sphere = fibonacciSphere(14000)
  .filter((p) => geoContains(land, p))
  .map(([lon, lat]) => [Math.round(lon * 10) / 10, Math.round(lat * 10) / 10]);

/* ---- 2. lat/lon grid sampling for the flat map ---- */
const grid = [];
for (let lat = -56; lat <= 78; lat += 2) {
  for (let lon = -180; lon <= 180; lon += 2) {
    if (geoContains(land, [lon, lat])) grid.push([lon, lat]);
  }
}

/* ---- 3. equirectangular outline ---- */
const projection = geoEquirectangular().fitSize([1000, 500], land);
const pathGen = geoPath(projection);
const landD = pathGen(land);

/* ---- 4. anchor regions, geographically spread ---- */
const REGIONS = [
  ["North America", -98.5, 39.8],
  ["Brazil", -51.9, -14.2],
  ["Chile", -71.5, -35.7],
  ["West Africa", -3.0, 8.0],
  ["Kenya", 37.9, 0.2],
  ["France", 2.2, 46.2],
  ["Nordics", 15.5, 62.0],
  ["Egypt", 30.8, 26.8],
  ["India", 78.9, 20.6],
  ["Singapore", 103.8, 1.35],
  ["Japan", 138.2, 36.2],
  ["Korea", 127.8, 36.5],
  ["Australia", 134.5, -25.7],
  ["Indonesia", 113.9, -2.5],
];

const out = `/* Generated by .geobuild/gen.mjs from Natural Earth (world-atlas land-50m).
   Public domain. Do not hand-edit; regenerate instead. */
window.GEO = {
  SPHERE: ${JSON.stringify(sphere)},
  GRID: ${JSON.stringify(grid)},
  LAND_D: ${JSON.stringify(landD)},
  REGIONS: ${JSON.stringify(REGIONS)}
};
`;

process.stdout.write(out);
process.stderr.write(
  `sphere pts: ${sphere.length}\ngrid pts: ${grid.length}\npath length: ${landD.length}\n`
);
