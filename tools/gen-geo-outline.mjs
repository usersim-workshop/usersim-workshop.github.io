// The 50m outline is ~910KB, far too heavy to ship. Rebuild LAND_D from the
// 110m land at reduced precision, reusing the already-sampled point arrays
// (which are cheap to store and took ~70s to compute).

import { readFileSync, writeFileSync } from "node:fs";
import * as topojson from "topojson-client";
import { geoPath, geoEquirectangular } from "d3-geo";

const src = readFileSync("../geo-data.js", "utf8");
const grab = (key) => {
  const m = src.match(new RegExp(`${key}: (\\[[\\s\\S]*?\\]),\\n`));
  if (!m) throw new Error(`could not find ${key}`);
  return m[1];
};

const sphere = grab("SPHERE");
const grid = grab("GRID");
const regions = src.match(/REGIONS: (\[[\s\S]*?\])\n\};/)[1];

const topo = JSON.parse(readFileSync("node_modules/world-atlas/land-110m.json", "utf8"));
const land = topojson.feature(topo, topo.objects.land);

const projection = geoEquirectangular().fitSize([1000, 500], land);
// One decimal place is well below a pixel at our render sizes.
const landD = geoPath(projection).digits(1)(land);

writeFileSync(
  "../geo-data.js",
  `/* Generated by .geobuild from Natural Earth (world-atlas).
   Land samples from land-50m, outline from land-110m. Public domain.
   Do not hand-edit; regenerate with gen.mjs + patch-path.mjs. */
window.GEO = {
  SPHERE: ${sphere},
  GRID: ${grid},
  LAND_D: ${JSON.stringify(landD)},
  REGIONS: ${regions}
};
`
);

console.error(`outline path length: ${landD.length}`);
